    public void iniciarLabel(int x, int y, JLabel label, String op, String texto) {
        label.setText(texto);
        //label.setBorder(BorderFactory.createLineBorder(Color.yellow, 2));
        label.setOpaque(false);
        label.setBounds(x, y, 260, 60);
        label.setFont(new Font("Segoe UI", Font.BOLD, 20));
        label.setForeground(new Color(6, 16, 84));
//        if(!texto.equals("Avançar")){
//            return;
//        }
        label.addMouseListener(new MouseAdapter() {

            @Override
            public void mouseEntered(MouseEvent e) {
                setCursor(new Cursor(Cursor.HAND_CURSOR));
            }

            @Override
            public void mouseExited(MouseEvent e) {
                setCursor(new Cursor(Cursor.DEFAULT_CURSOR));
            }

            @Override
            public void mouseClicked(MouseEvent e) {
                dispose();
                new Class(timesGrupoA, timesGrupoB, "Godoiense ").setVisible(true);
            }
        });
    }

    private List<Time> buscarGrupoA() {
        DadosService dadosService = new DadosService();
        Dados dados = dadosService.lerDados();
        return dados.getTemporadas().get(0).getGrupos().get(0).getTimes();

    }

    private List<Time> buscarGrupoB() {
        DadosService dadosService = new DadosService();
        Dados dados = dadosService.lerDados();
        return dados.getTemporadas().get(0).getGrupos().get(1).getTimes();

    }

